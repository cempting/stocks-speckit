import yaml,re,collections,sys,os
ROOT=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DOCS=os.path.join(ROOT,"docs"); SPEC=os.path.join(ROOT,"specs")
Y=os.path.join(DOCS,"glossary/glossary.yaml"); M=os.path.join(DOCS,"glossary/glossary.md")
d=yaml.safe_load(open(Y)); terms=d['terms']; ids={t['id'] for t in terms}
TITLES={'A01':'Market structure & instruments','A02':'Market regime & scoreboard','A03':'Business cycle & macro indicators','A04':'Money flow & volume','A05':'Security selection','A06':'Entry rules','A07':'Exit & selling','A08':'Risk & position sizing','A09':'Portfolio construction','A10':'Fixed income','A11':'Macro themes','A12':'Process, routine & psychology','A13':'Strategy profiles'}
if len(sys.argv)>1 and sys.argv[1]=="add":
    # harvest section-9 glossary additions from aspect files
    import glob
    add={}
    for f in sorted(glob.glob(os.path.join(SPEC,"aspect/A*.md"))):
        asp=re.search(r"/(A\d\d)-",f)[1]; txt=open(f).read()
        m=re.search(r"(?is)glossary additions.*?(?=\n## |\Z)",txt)
        if not m: continue
        for line in m.group(0).splitlines():
            line=line.strip()
            r=re.match(r"^\|\s*`?([a-z0-9-]+)`?\s*\|\s*([^|]+)\|\s*(CORE|METHOD|MACRO|PROFILE)\s*\|\s*([^|]+)\|\s*([^|]*)\|",line) or \
              re.match(r"^-\s*`([a-z0-9-]+)`\s*\|\s*([^|]+)\|\s*(CORE|METHOD|MACRO|PROFILE)\s*\|\s*([^|]+)\|\s*(.*)$",line)
            if not r or r[1] in ('slug',): continue
            slug,term,layer,defi,src=[x.strip() for x in r.groups()]
            if slug in ids or slug in add: print("dup",slug,asp); continue
            srcs=re.findall(r"S\d\d",src); decs=re.findall(r"D-[A-Z0-9-]+",src)
            add[slug]=dict(id=slug,term=term,layer=layer,kind='concept',aspects=[asp],definition=defi,synonyms=[],deprecated_synonyms=[],related=[],sources=srcs, **({'decisions':decs} if decs else {}))
    # merge duplicates
    add.pop('allocated-gold',None)
    for s in add: print("add",s)
    terms.extend(add.values())
    for t in terms:
        if t['id']=='allocated-storage': t['synonyms']=sorted(set(t.get('synonyms',[])+['allocated gold']))
    order={k:i for i,k in enumerate(TITLES)}
    terms.sort(key=lambda t:(order[t['aspects'][0]],t['term'].lower()))
    d['version']='0.2.0'
    hdr=open(Y).read().split('\n')[0]
    with open(Y,'w') as fh:
        fh.write(hdr+"\n"); yaml.safe_dump(d,fh,sort_keys=False,allow_unicode=True,width=110)
    d=yaml.safe_load(open(Y)); terms=d['terms']
# validate
ids=[t['id'] for t in terms]; assert len(ids)==len(set(ids)),"dup ids"
bad=[(t['id'],r) for t in terms for r in t.get('related',[]) if r not in ids]; assert not bad,bad
# regenerate md, preserving deprecated section
old=open(M).read(); dep=old[old.index("## Deprecated / ambiguous terms"):]
lc=collections.Counter(t['layer'] for t in terms); ac=collections.Counter(t['aspects'][0] for t in terms)
cell=lambda s:str(s).replace("|","\\|").replace("\n"," ").strip()
out=[f"""---
id: GLOSSARY
version: {d['version']}
title: Domain Glossary
status: draft
layers:
  CORE: neutral financial-markets domain, valid for any strategy
  METHOD: canonical Follow-the-Money method (scoreboard, basket, heartbeat, purple line ...)
  PROFILE: non-canonical strategy profiles (prf-beginner-index, prf-momentum-rotation)
  MACRO: macro/thematic knowledge modelled as theses and dated observations, never as rules
term_count: {len(terms)}
source: glossary.yaml (this file is generated by tools/gen_glossary.py; do not edit by hand)
---

# Domain Glossary

This glossary is the controlled vocabulary of the spec and the vocabulary of the DSL. Every concept used in aspect specs, rules and entities MUST be a glossary term and SHOULD be referenced by its slug as `[[slug]]` (e.g. [[purple-line]]). Definitions live only here; aspect specs reference them.

- **Layer** says where a term belongs (CORE / METHOD / PROFILE / MACRO).
- **Kind** is one of: concept, entity, instrument, indicator, signal, metric, rule-concept, process, role, event, thesis, pattern, order-type, classification.
- Terms are grouped by primary aspect; secondary aspects, parameters, formulas, related terms and decision references are in the YAML.
- Synonyms are accepted input wordings (from sources); deprecated synonyms MUST NOT be used in new text.
- No value is open: every former open point is decided (`D-R…`) or set by a reviewable default (`D-DEF-…`, pending user review; see ../../specs/decisions.md).
- Sources `[]` with the note 'standard term, added for completeness' means the term is not defined in the sources.

## Counts

| Layer | Terms |
|---|---|"""]
out+= [f"| {k} | {lc[k]} |" for k in ['CORE','METHOD','PROFILE','MACRO']]
out+=["","| Aspect | Title | Terms |","|---|---|---|"]+[f"| {a} | {TITLES[a]} | {ac[a]} |" for a in TITLES]
for a in TITLES:
    out+=["",f"## {a} — {TITLES[a]}","","| Term (`slug`) | Layer | Kind | Definition | Synonyms | Sources |","|---|---|---|---|---|---|"]
    for t in terms:
        if t['aspects'][0]==a:
            out.append(f"| **{cell(t['term'])}** (`{t['id']}`) | {t['layer']} | {t.get('kind','')} | {cell(t['definition'])} | {cell('; '.join(t.get('synonyms',[])))} | {', '.join(t.get('sources',[]))} |")
idx=[]
for t in terms:
    idx.append((t['term'],t['id'],''))
    for s in t.get('synonyms',[]): idx.append((s,t['id'],' (synonym)'))
    for s in t.get('deprecated_synonyms',[]): idx.append((s,t['id'],' (deprecated)'))
idx.sort(key=lambda x:x[0].lower())
out+=["","## Alphabetical index","","Display names and synonyms, mapped to slugs.",""]+[f"- {n}{k} → `{i}`" for n,i,k in idx]
out+=["",dep.rstrip(),""]
open(M,'w').write("\n".join(out))
open(os.path.join(DOCS,"glossary/term_ids.txt"),"w").write("\n".join(f"{t['id']} | {t['term']} | {t['layer']} | {t['aspects'][0]}" for t in terms)+"\n")
print("terms",len(terms),dict(lc))
